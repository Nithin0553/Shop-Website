test('IST daily calendar date and per-day posts have stable IDs',()=>{
  assert.equal(indiaDate(now),date);
  assert.equal(indiaDate(new Date('2026-11-19T20:00:00Z')),date);
  assert.equal(slugify('Battery & Scooter Guide!'),'battery-scooter-guide');
});

test('Google News metadata is filtered without downloading or copying articles',()=>{
  const items=parseNewsFeed(rss,now);
  assert.equal(items.length,1);
  assert.equal(items[0].source,'Example Daily');
  assert.equal(items[0].date,'2026-11-19');
  assert.equal(items[0].url,'https://news.google.com/rss/articles/TESTFEED');
  const outdated=rss.replace('19 Nov 2026','01 Aug 2026');
  assert.equal(parseNewsFeed(outdated,now).length,0);
  assert.ok(NEWS_FEEDS.every(url=>url.startsWith('https://news.google.com/rss/')));
});

test('editorial selection favors unused, original Indian bike and scooter topics',()=>{
  const guide=chooseTopic(existing,[],date);
  assert.ok(TOPICS.some(topic=>guide.key.startsWith(topic.key+'-')));
  assert.ok(['Maintenance Tips','Spare Parts Guide','Buying Guide','Bike Care','Scooter Care'].includes(guide.category));
  assert.ok(similarity('Battery Care Guide','Battery and Care Guide')>0.7);
});

test('article validator enforces useful structure and rejects duplicates or markup',()=>{
  const topic=chooseTopic(existing,[],date);
  const valid=validateDraft(mockDraft,existing,topic,date);
  assert.equal(valid.status,'published');
  assert.equal(valid.autoGenerated,true);
  assert.equal(valid.publishedAt,date);
  assert.equal(valid.image,topic.image);
  assert.ok(valid.body.includes('Prepared with AI assistance'));
  assert.ok(valid.slug.endsWith('-20261120'));
  assert.throws(()=>validateDraft({...mockDraft,body:'Too short'},existing,topic,date),/too short/);
  assert.throws(()=>validateDraft({...mockDraft,title:'When Should You Replace Brake Parts?'},existing,topic,date),/similar/);
  assert.throws(()=>validateDraft({...mockDraft,body:mockDraft.body+'<script>alert(1)</script>'},existing,topic,date),/markup/);
});

test('Gemini request sends the key only in a private header and validates JSON response',async()=>{
  const prompt=makePrompt(chooseTopic(existing,[],date),existing,date);
  assert.ok(prompt.includes('untrusted third-party'));
  assert.ok(prompt.includes('owner manuals'));
  let calls=0;
  const fake=async (url,options)=>{
    calls++;
    assert.match(url,/generativelanguage\.googleapis\.com\/v1beta\/models\/gemini-3\.8-flash:generateContent/);
    assert.equal(options.headers['x-goog-api-key'],'private-test-key');
    assert.equal(JSON.stringify(options.body).includes('private-test-key'),false);
    return {ok:true,status:200,json:async()=>({candidates:[{finishReason:'STOP',
      content:{parts:[{text:JSON.stringify(mockDraft)}]}}]})};
  };
  const result=await requestGeminiDraft(prompt,'private-test-key',fake);
  assert.equal(calls,1);
  assert.equal(result.title,mockDraft.title);
  await assert.rejects(requestGeminiDraft(prompt,'',fake),/GEMINI_API_KEY/);
});

test('Gemini 404 on a restricted model tries an accessible Flash-Lite alternative',async()=>{
  const models=[];
  const fetcher=async url=>{
    const candidate=url.split('/models/')[1].split(':')[0];
    models.push(candidate);
    if(candidate==='gemini-2.5-flash-lite')return {ok:false,status:404};
    return {ok:true,status:200,json:async()=>({candidates:[{finishReason:'STOP',
      content:{parts:[{text:JSON.stringify(mockDraft)}]}}]})};
  };
  const output=await requestGeminiDraft('test prompt','private-test-key',fetcher,'gemini-2.5-flash-lite');
  assert.equal(output.title,mockDraft.title);
  assert.deepEqual(models,['gemini-2.5-flash-lite','gemini-3.6-flash']);
});

