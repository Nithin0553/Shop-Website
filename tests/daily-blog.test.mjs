import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  indiaDate, NEWS_FEEDS, TOPICS, parseNewsFeed, chooseTopic,
  slugify, similarity, validateDraft
} from '../scripts/auto-blog-content.mjs';
import {prepareDailyArticle, requestGeminiDraft, runDaily,makePrompt} from '../scripts/daily-blog.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const existing=JSON.parse(readFileSync(path.join(root,'data/blogs.json'),'utf8'));
const now=new Date('2026-11-20T06:00:00.000Z');
const date='2026-11-20';
const mockBody=['Introduction: Daily riders in India can make practical checks without taking apart the vehicle. '
  +'Always follow the owner manual for model-specific intervals, specifications and tolerances.'],
  safeHeading='## Safe checks before riding',
  paragraph='An owner can look for obvious wear, damage, leaks and unusual sounds while the vehicle is parked safely. '
  +'Keep attention on roadworthiness and ask a trained technician about unclear symptoms. '
  +'Different motorcycles and scooters need different parts and maintenance intervals. '
  +'It is safer to verify the vehicle model and actual part number than to guess from a photograph.',
  sections=['Safe checks before riding','How to confirm the right part','Questions for a technician',
    'Common mistakes to avoid','When to stop and seek help','Final checklist'];
const fullBody=mockBody[0]+'\n\n'+sections.map(title=>'## '+title+'\n'+paragraph+' '+paragraph).join('\n\n');
const mockDraft={
  title:'A Practical Check Before Buying Two-Wheeler Replacement Parts',
  summary:'A rider-focused checklist for checking fit, wear signs and professional support before purchasing compatible spare parts.',
  body:fullBody
};
const rss='<rss><channel><item><title><![CDATA[New India motorcycle and scooter safety initiative - Example Daily]]></title>'+
  '<link>https://news.google.com/rss/articles/TESTFEED</link>'+
  '<pubDate>Thu, 19 Nov 2026 11:00:00 GMT</pubDate><source>Example Daily</source></item>'+
  '<item><title>Truck exports continue</title><link>https://news.google.com/rss/articles/TRUCK</link>'+
  '<pubDate>Thu, 19 Nov 2026 11:00:00 GMT</pubDate></item>'+
  '</channel></rss>';

test('IST daily calendar date and per-day posts have stable IDs',()=>{
  assert.equal(indiaDate(now),date);
  assert.equal(indiaDate(new Date('2026-11-19T20:00:00Z')),date);
  assert.equal(slugify('Battery & Scooter Guide!'),'battery-scooter-guide');
});

test('Google News metadata is filtered without downloading or copying articles',()=>{
  const items=parseNewsFeed(rss,now);
  assert.equal(items.length,1);
  assert.equal(items[0].source,'Example Daily');
  assert.equal(items[0].date,'2026-11-19');
  assert.equal(items[0].url,'https://news.google.com/rss/articles/TESTFEED');
  const outdated=rss.replace('19 Nov 2026','01 Aug 2026');
  assert.equal(parseNewsFeed(outdated,now).length,0);
  assert.ok(NEWS_FEEDS.every(url=>url.startsWith('https://news.google.com/rss/')));
});

test('editorial selection favors unused, original Indian bike and scooter topics',()=>{
  const guide=chooseTopic(existing,[],date);
  assert.ok(TOPICS.some(topic=>topic.key===guide.key));
  assert.ok(['Maintenance Tips','Spare Parts Guide','Buying Guide','Bike Care','Scooter Care'].includes(guide.category));
  assert.ok(similarity('Battery Care Guide','Battery and Care Guide')>0.7);
});

test('article validator enforces useful structure and rejects duplicates or markup',()=>{
  const topic=chooseTopic(existing,[],date);
  const valid=validateDraft(mockDraft,existing,topic,date);
  assert.equal(valid.status,'published');
  assert.equal(valid.autoGenerated,true);
  assert.equal(valid.publishedAt,date);
  assert.equal(valid.image,topic.image);
  assert.ok(valid.body.includes('Prepared with AI assistance'));
  assert.ok(valid.slug.endsWith('-20261120'));
  assert.throws(()=>validateDraft({...mockDraft,body:'Too short'},existing,topic,date),/too short/);
  assert.throws(()=>validateDraft({...mockDraft,title:'When Should You Replace Brake Parts?'},existing,topic,date),/similar/);
  assert.throws(()=>validateDraft({...mockDraft,body:mockDraft.body+'<script>alert(1)</script>'},existing,topic,date),/markup/);
});

test('Gemini request sends the key only in a private header and validates JSON response',async()=>{
  const prompt=makePrompt(chooseTopic(existing,[],date),existing,date);
  assert.ok(prompt.includes('untrusted third-party'));
  assert.ok(prompt.includes('owner manuals'));
  let calls=0;
  const fake=async (url,options)=>{
    calls++;
    assert.match(url,/generativelanguage\.googleapis\.com\/v1beta\/models\/gemini-2\.5-flash-lite:generateContent/);
    assert.equal(options.headers['x-goog-api-key'],'private-test-key');
    assert.equal(JSON.stringify(options.body).includes('private-test-key'),false);
    return {ok:true,status:200,json:async()=>({candidates:[{finishReason:'STOP',
      content:{parts:[{text:JSON.stringify(mockDraft)}]}}]})};
  };
  const result=await requestGeminiDraft(prompt,'private-test-key',fake);
  assert.equal(calls,1);
  assert.equal(result.title,mockDraft.title);
  await assert.rejects(requestGeminiDraft(prompt,'',fake),/GEMINI_API_KEY/);
});

test('dry-run generates valid preview without modifying the original blog file',async()=>{
  const snapshot=readFileSync(path.join(root,'data/blogs.json'),'utf8');
  const feedFetcher=async()=>({ok:true,status:200,text:async()=>rss});
  const modelFetcher=async()=>({ok:true,status:200,json:async()=>({candidates:[
    {finishReason:'STOP',content:{parts:[{text:JSON.stringify(mockDraft)}]}}
  ]})});
  const result=await runDaily({now,existing,dryRun:true,key:'fake-test-key',feedFetcher,modelFetcher});
  assert.equal(result.status,'ready');
  assert.equal(result.article.id,'auto-2026-11-20');
  assert.equal(readFileSync(path.join(root,'data/blogs.json'),'utf8'),snapshot);
  const again=await prepareDailyArticle({now,existing:[{...result.article},...existing],key:'',
    feedFetcher:()=>{throw Error('Should not call news when already published');}});
  assert.equal(again.status,'already-published');
});

test('scheduled publishing is timezone-aware and deploys in the same run',()=>{
  const workflow=readFileSync(path.join(root,'.github/workflows/daily-blog.yml'),'utf8');
  assert.match(workflow,/cron: '37 8 \* \* \*'/);
  assert.match(workflow,/timezone: 'Asia\/Kolkata'/);
  assert.match(workflow,/contents: write/);
  assert.match(workflow,/GEMINI_API_KEY: \$\{\{ secrets\.GEMINI_API_KEY \}\}/);
  assert.match(workflow,/BEFORE committing/);
  assert.match(workflow,/git push origin HEAD:main/);
  assert.match(workflow,/actions\/upload-pages-artifact@v4/);
  assert.match(workflow,/actions\/deploy-pages@v4/);
  const order=['node scripts/daily-blog.mjs','npm test','npm run github:build','git commit -m','actions/upload-pages-artifact@v4'];
  let previous=-1;
  for(const term of order) {
    const index=workflow.indexOf(term);
    assert.ok(index>previous,term+' must be ordered after earlier steps');
    previous=index;
  }
});
